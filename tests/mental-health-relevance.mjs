import assert from 'node:assert/strict';
import { mkdir } from 'node:fs/promises';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const require = createRequire(import.meta.url);
const { chromium } = require(process.env.PLAYWRIGHT_PACKAGE || 'playwright');
const base = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const shots = path.join(base, 'shots', 'mental-health-relevance');
await mkdir(shots, { recursive: true });
const browser = await chromium.launch({ headless: true, ...(process.env.PLAYWRIGHT_CHANNEL ? { channel: process.env.PLAYWRIGHT_CHANNEL } : {}) });
const context = await browser.newContext({ viewport: { width: 1440, height: 1100 }, deviceScaleFactor: 1 });
const page = await context.newPage();
const errors = [];
const remoteRequests = [];
page.on('pageerror', (error) => errors.push(String(error)));
page.on('request', (request) => { if (/^https?:/i.test(request.url())) remoteRequests.push(request.url()); });
await page.goto(new URL('../index.html#mental-health-relevance', import.meta.url).href);
await page.getByRole('heading', { name: 'Before you begin' }).waitFor();
await page.screenshot({ path: path.join(shots, 'instructions.png'), fullPage: true });
await page.getByRole('button', { name: 'Open annotation preview' }).click();
assert.equal(await page.locator('input[name=mental_health_relevance]:checked').count(), 0);
assert.equal(await page.locator('iframe').count(), 0);
assert.equal(await page.locator('.mh-screenshots[open]').count(), 0);
const quickGuide = page.getByRole('region', { name: 'Quick guide', exact: true });
await quickGuide.waitFor({ state: 'visible' });
assert.ok((await quickGuide.innerText()).includes('Choose Related when mental health is a substantial topic of the video. Examples include depression and anxiety, other mental-health conditions, personal experiences or symptoms, suicide or self-harm, coping, treatment, access to care, stigma, support, and recovery.'));
for (const emphasis of ['Related', 'substantial topic', 'depression and anxiety']) {
  assert.ok(await quickGuide.locator('strong').filter({ hasText: new RegExp(`^${emphasis}$`) }).count(), `${emphasis} is emphasized`);
}
assert.ok((await quickGuide.boundingBox()).y < (await page.locator('.mh-answer-options').boundingBox()).y, 'Quick guide appears before answer choices');
assert.equal(await page.locator('.mh-answer-hint').count(), 0, 'No duplicate helper sentence below choices');
await page.screenshot({ path: path.join(shots, 'desktop.png'), fullPage: true });
await page.getByRole('button', { name: 'Play preview', exact: true }).click();
await page.getByRole('button', { name: 'Pause preview', exact: true }).waitFor();
await page.getByRole('button', { name: 'Take a break' }).click();
await page.getByRole('button', { name: 'Return to preview' }).click();
await page.getByRole('button', { name: 'Play preview', exact: true }).waitFor();
await page.getByRole('button', { name: 'Save & next', exact: true }).click();
await page.getByText('Choose one answer before saving.').waitFor();
await page.getByRole('radio', { name: 'Related', exact: true }).check();
await page.getByText('Draft kept in this tab · not yet completed').waitFor();
assert.match(await page.locator('.mh-progress').innerText(), /0 of 3/);
await page.getByRole('button', { name: 'Take a break' }).click();
assert.equal(await page.locator('.mh-player').count(), 0);
await page.getByRole('button', { name: 'Return to preview' }).click();
assert.equal(await page.getByRole('radio', { name: 'Related', exact: true }).isChecked(), true);
await page.locator('.mh-preview-controls details summary').click();
await page.getByRole('button', { name: 'Simulate next save failing' }).click();
await page.getByRole('button', { name: 'Save & next', exact: true }).click();
await page.getByText(/Example save failure/).waitFor();
assert.match(await page.locator('.mh-progress').innerText(), /0 of 3/);
assert.equal(await page.getByRole('radio', { name: 'Related', exact: true }).isChecked(), true);
await page.getByRole('button', { name: 'Save & next', exact: true }).click();
assert.match(await page.locator('.mh-progress').innerText(), /1 of 3/);
assert.match(await page.locator('.mh-video-bar').innerText(), /YouTube/);
await page.getByRole('radio', { name: 'Not related / insufficient evidence', exact: true }).check();
await page.getByRole('button', { name: 'Save & leave' }).click();
await page.getByRole('button', { name: 'Return to preview' }).click();
assert.equal(await page.getByRole('radio', { name: 'Not related / insufficient evidence', exact: true }).isChecked(), true);
await page.getByRole('button', { name: 'Save & next', exact: true }).click();
assert.match(await page.locator('.mh-progress').innerText(), /2 of 3/);
await page.getByRole('heading', { name: 'Video unavailable', exact: true }).waitFor();
assert.equal(await page.locator('input[name=mental_health_relevance]:checked').count(), 0);
await page.getByText('Video unavailable? View 1 screenshot', { exact: true }).click();
await page.getByRole('button', { name: 'Enlarge screenshot 1' }).click();
await page.getByRole('heading', { name: 'Screenshot 1 of 1' }).waitFor();
await page.keyboard.press('Escape');
assert.equal(await page.getByRole('button', { name: 'Enlarge screenshot 1' }).evaluate((el) => el === document.activeElement), true);
await page.getByRole('button', { name: '1. TikTok', exact: true }).click();
assert.equal(await page.getByRole('radio', { name: 'Related', exact: true }).isChecked(), true);
await page.getByText('Video unavailable? View 3 screenshots', { exact: true }).click();
await page.getByRole('button', { name: 'Enlarge screenshot 1' }).click();
await page.keyboard.press('ArrowRight');
await page.getByRole('heading', { name: 'Screenshot 2 of 3' }).waitFor();
await page.keyboard.press('ArrowLeft');
await page.getByRole('heading', { name: 'Screenshot 1 of 3' }).waitFor();
await page.keyboard.press('Escape');
await page.locator('.mh-preview-controls details summary').click();
await page.getByRole('button', { name: 'Reset this preview' }).click();
await page.getByRole('button', { name: 'Open annotation preview' }).click();
await page.getByRole('radio', { name: 'Related', exact: true }).check();
await page.getByRole('button', { name: 'Skip for now', exact: true }).click();
await page.getByRole('heading', { name: 'Leave this answer unfinished?' }).waitFor();
await page.locator('#dlg [data-dlg=confirm]').click();
assert.match(await page.locator('.mh-progress').innerText(), /0 of 3/);
await page.getByRole('button', { name: 'Prefer not to view', exact: true }).click();
await page.locator('#dlg [data-dlg=confirm]').click();
assert.match(await page.locator('.mh-progress').innerText(), /0 of 3/);
assert.equal(await page.getByRole('button', { name: '2. YouTube', exact: true }).isDisabled(), true);
await page.getByRole('button', { name: 'Skip for now', exact: true }).click();
assert.equal(await page.getByRole('radio', { name: 'Related', exact: true }).isChecked(), true, 'Skipped draft retained on return');

// Reset before screenshots; no fabricated saved responses are presented as study work.
await page.locator('.mh-preview-controls details summary').click();
await page.getByRole('button', { name: 'Reset this preview' }).click();
await page.getByRole('button', { name: 'Open annotation preview' }).click();
await page.setViewportSize({ width: 390, height: 844 });
await page.screenshot({ path: path.join(shots, 'mobile.png'), fullPage: true });
assert.equal(await quickGuide.isVisible(), true, 'Guide stays visible on mobile without expanding anything');
assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), true, 'No mobile horizontal overflow');
const playerBox = await page.locator('.mh-video-card').boundingBox();
const answerBox = await page.locator('.mh-answer-panel').boundingBox();
assert.ok(answerBox.y > playerBox.y + playerBox.height, 'Answer panel stacks below video on mobile');
for (const width of [320, 768, 1024]) {
  await page.setViewportSize({ width, height: 900 });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), true, `No horizontal overflow at ${width}px`);
}
await page.reload();
await page.getByRole('heading', { name: 'Before you begin' }).waitFor();
await page.getByRole('button', { name: 'Open annotation preview' }).click();
assert.match(await page.locator('.mh-progress').innerText(), /0 of 3/);
assert.equal(await page.locator('input[name=mental_health_relevance]:checked').count(), 0);
await page.goto(new URL('../index.html#annotator', import.meta.url).href);
await page.getByRole('heading', { name: 'Labeling public posts, one item at a time' }).waitFor();
assert.equal(await page.locator('#view-mental-health-relevance').isVisible(), false);
await page.goto(new URL('../index.html#manager', import.meta.url).href);
await page.getByRole('heading', { name: 'Running a study, from upload to export' }).waitFor();
assert.deepEqual(errors, []);
assert.deepEqual(remoteRequests, [], 'Preview and old tours made zero external network requests, including annotation APIs');
await browser.close();
console.log(JSON.stringify({ passed: true, screenshots: shots, externalRequests: remoteRequests.length }, null, 2));
